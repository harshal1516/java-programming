public class Switch2 {
    public static void main(String[] args) {
        int ch ='a';
        switch(ch ){
            case 'a' : System.out.println("Samosa");
            break;

            case 'd' : System.out.println("Paratha");
            break;

            case 'c': System.out.println("MALKIST");
            break;
              
            default : System.out.println("DAYDREMAING");
             
        }
    }
    
}
